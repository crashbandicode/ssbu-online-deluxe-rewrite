pub fn needs_context(hash: u64) -> bool {
    CONTEXT_HASHES.binary_search(&hash).is_ok()
}
/// Shadow Flare's Reduced cue is a sibling file, not an Off target added here.
const EDGE_SIDE_B: [u64; 0] = [];

pub fn scoped(profile: Profile, hash: u64) -> bool {
    let hashes: &[u64] = match profile {
        Profile::KazuyaFSmash => &KAZUYA_F_SMASH,
        Profile::FalconPunch => &FALCON_PUNCH,
        Profile::NessUpB => &NESS_UP_B,
        Profile::LucasUpB => &LUCAS_UP_B,
        Profile::IkeNeutralB => &IKE_NEUTRAL_B,
        Profile::ChromNeutralB => &CHROM_NEUTRAL_B,
        Profile::RoyNeutralB => &ROY_NEUTRAL_B,
        Profile::PalutenaRapidJab => &PALUTENA_RAPID_JAB,
        Profile::PalutenaNeutralB => &PALUTENA_NEUTRAL_B,
        Profile::PalutenaUpB => &PALUTENA_UP_B,
        Profile::PalutenaSideB => &PALUTENA_SIDE_B,
        Profile::PalutenaUpSmash => &PALUTENA_UP_SMASH,
        Profile::PalutenaTilts => &PALUTENA_TILTS,
        Profile::PalutenaWingSmash => &PALUTENA_WING_SMASH,
        Profile::PalutenaUpAir => &PALUTENA_UP_AIR,
        Profile::EdgeNeutralB => &EDGE_NEUTRAL_B,
        Profile::EdgeDownB => &EDGE_DOWN_B,
        Profile::EdgePurpleDash => &EDGE_PURPLE_DASH,
        Profile::EdgeFSmash => &EDGE_F_SMASH,
        Profile::EdgeSideB => &EDGE_SIDE_B,
    };
    hashes.binary_search(&hash).is_ok()
}

